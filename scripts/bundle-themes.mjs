// Packs themes/<name>/ into lib/builtin-themes.mjs so the server needs no file access at runtime.
//   node scripts/bundle-themes.mjs          (run after changing anything in themes/)
//   node scripts/bundle-themes.mjs --check  (fails if the bundle is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkPackage } from '../lib/theme.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'themes'), out = path.join(root, 'lib', 'builtin-themes.mjs');
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const themes = {};
for (const name of fs.readdirSync(dir).filter(n => fs.statSync(path.join(dir, n)).isDirectory()).sort()) {
  const base = path.join(dir, name), files = {};
  for (const f of walk(base).sort()) files[path.relative(base, f).split(path.sep).join('/')] = fs.readFileSync(f);
  checkPackage(files); // throws if a built-in theme is broken
  themes[name] = Object.fromEntries(Object.entries(files).map(([k, b]) => [k, b.toString('base64')]));
}
const src = `// Generated by scripts/bundle-themes.mjs from themes/. Do not edit by hand.\nexport default ${JSON.stringify(themes, null, 1)};\n`;
if (process.argv.includes('--check')) { if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== src) { console.error('lib/builtin-themes.mjs is out of date: run node scripts/bundle-themes.mjs'); process.exit(1); } console.log('built-in themes up to date'); }
else { fs.writeFileSync(out, src); console.log('bundled', Object.keys(themes).join(', ')); }
